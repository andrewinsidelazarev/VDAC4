def glyph(ch, size):
    """Готовая маска с полями; advance совпадает с шириной маски."""
    ss = 4
    unit = size / 12
    if ch in (' ', '\xa0'):
        return Image.new('L', (max(3, round(size * .32)), size + 2))
    if 0x2500 <= ord(ch) <= 0x259f:
        w, h = round(size * .65), size + 2
        im = Image.new('L', (w*ss, h*ss))
        d = ImageDraw.Draw(im)
        name = unicodedata.name(ch, '')
        if 'BLOCK' in name:
            box = [0, 0, w*ss-1, h*ss-1]
            if 'UPPER' in name: box[3] //= 2
            if 'LOWER' in name: box[1] = h*ss//2
            if 'LEFT' in name: box[2] //= 2
            if 'RIGHT' in name: box[0] = w*ss//2
            d.rectangle(box, fill=255)
        elif 'SHADE' in name:
            for y in range(h):
                for x in range(w):
                    if (x+y*3) % 4 < {'░': 1, '▒': 2, '▓': 3}[ch]:
                        d.rectangle((x*ss,y*ss,(x+1)*ss-1,(y+1)*ss-1),fill=255)
        else:
            cx, cy = w*ss//2, h*ss//2
            dirs = []
            if 'HORIZONTAL' in name: dirs += [(0,cy),(w*ss,cy)]
            if 'VERTICAL' in name: dirs += [(cx,0),(cx,h*ss)]
            for word, end in [('LEFT',(0,cy)),('RIGHT',(w*ss,cy)),('UP',(cx,0)),('DOWN',(cx,h*ss))]:
                if word in name: dirs.append(end)
            for end in dirs:
                d.line([(cx,cy),end],fill=255,width=ss)
                if 'DOUBLE' in name:
                    dx,dy = (0,2*ss) if end[1]==cy else (2*ss,0)
                    d.line([(cx+dx,cy+dy),(end[0]+dx,end[1]+dy)],fill=255,width=ss)
        return im.resize((w,h),Image.Resampling.LANCZOS)
    spec = SHAPES.get(ch, SHAPES['?'])
    paths = [[tuple(map(float,p.split(','))) for p in s.split()] for s in spec.split(';')]
    minx = min(x for s in paths for x,y in s)
    maxx = max(x for s in paths for x,y in s)
    w = max(3, round((maxx-minx+2.35)*unit))
    im = Image.new('L',(w*ss,(size+2)*ss))
    d = ImageDraw.Draw(im)
    stroke = max(4,round(unit*1.10*ss))
    for path in paths:
        xy = [((x-minx+.7)*unit*ss,(y+1.3)*unit*ss) for x,y in path]
        d.line(xy,fill=255,width=stroke,joint='curve')
        r = stroke/2-.2
        for x,y in xy:
            d.ellipse((x-r,y-r,x+r,y+r),fill=255)
    return im.resize((w,size+2),Image.Resampling.LANCZOS)


def draw_text(image, xy, text, size, color):
    x,y = xy
    for ch in text:
        g = glyph(ch,size)
        image.paste(color,(x,y),g)
        x += g.width
    return x


def main():
    out = ROOT/'fonts'
    out.mkdir(exist_ok=True)
    arrays, tables, total = [], [], 0
    for size in SIZES:
        data, entries = [], []
        for code in range(32,256):
            ch = bytes([code]).decode('cp866')
            g = glyph(ch,size)
            values = [(v*15+127)//255 for v in g.tobytes()]
            entries.append((len(data),g.width,g.height))
            values += [0] if len(values)%2 else []
            data += [(values[i]<<4)|values[i+1] for i in range(0,len(values),2)]
        arrays.append(f'const uint8_t pixels{size}[] = {{\n'+ '\n'.join('  '+','.join(map(str,data[i:i+32]))+',' for i in range(0,len(data),32))+'\n};')
        arrays.append(f'const Glyph glyphs{size}[224] = {{\n'+'\n'.join(f'  {{{o},{w},{h}}},' for o,w,h in entries)+'\n};')
        tables.append(f'  {{pixels{size}, glyphs{size}, {size+2}}},')
        total += len(data) + len(entries)*8
    header = '''#pragma once
#include <stdint.h>
namespace pui_font {
struct Glyph { uint32_t offset; uint8_t width, height; };
struct Font { const uint8_t* pixels; const Glyph* glyphs; uint8_t height; };
extern const Font fonts[3];
}
'''
    (out/'pui_font.h').write_text(header,encoding='utf-8')
    (out/'pui_font.cpp').write_text('// Сгенерировано tools/generate_font.py; собственный PUI Sans.\n#include "pui_font.h"\nnamespace pui_font {\nnamespace {\n'+'\n'.join(arrays)+'\n}\nconst Font fonts[3] = {\n'+'\n'.join(tables)+'\n};\n}\n',encoding='utf-8')
    (out/'metrics.json').write_text(json.dumps({'sizes':SIZES,'glyphs_per_size':224,'table_bytes_including_glyph_padding':total},indent=2)+'\n',encoding='utf-8')
    print(f'PUI Sans: {total} bytes + descriptors')


if __name__ == '__main__':
    main()
