#pragma once

#include <stddef.h>
#include <stdint.h>

namespace zifi {

// Проверка образа ELF модуля до загрузчика components/elf_loader. Сам загрузчик
// размера файла не получает и верит заголовкам: смещения секций, индексы имён,
// символов и строк, адреса релокаций и точку входа берёт как есть, поэтому битый
// или чужой файл читает и пишет за границами памяти. Здесь проверяется всё, к чему
// он обращается (esp_elf_load_section и esp_elf_relocate при
// CONFIG_ELF_LOADER_BUS_ADDRESS_MIRROR): ELF32, little-endian, Xtensa; таблица
// секций и каждая секция с данными — в пределах файла; имена секций, символов и
// строки — с нулём внутри своих таблиц; у релокаций — индекс символа и место
// записи внутри загружаемой секции; точка входа — внутри .text.
// Выход: nullptr — образ годен, иначе причина отказа (строка-константа).
const char* elfImageProblem(const uint8_t* data, size_t size);

}  // namespace zifi
