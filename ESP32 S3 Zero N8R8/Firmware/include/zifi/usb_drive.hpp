#include "zifi/board.hpp"

#if ZIFI_HAS_USB_DRIVE

#include <stddef.h>
#include <stdint.h>

namespace zifi {

// Флешка в разъёме USB-C модуля: USB OTG ESP32-S3 работает хостом, флешка — том
// FAT32 или exFAT в /usb. На ней ядро держит:
// - кэш ресурсов музыки (/usb/SYSTEM/CACHE/MUSIC, ResourceDiskCache);
// - кэш приложений и модулей ESP (/usb/ELF, 0.1.146): ELF, которого нет в кэше
//   ESP, берётся с флешки, а не с карты Evo, и с флешки же запускается;
// - папку USB тома VDAC4 VFS.
//
// Хост включается при запуске ESP (0.1.146, 19.11.2026), через kPcCheckMs, если к
// разъёму не подключён ПК. С ПК разъём остаётся консолью USB Serial/JTAG (журнал,
// прошивка по USB), а флешки до перезапуска нет. Прежде хост включался при первом
// запросе ресурса музыки — когда плеер и декодер уже заняли внутреннюю память, и
// на плате (0.1.145) флешка не подключилась: «USBH: HCD Pipe alloc error:
// ESP_ERR_NO_MEM», свободно было 16 КБ внутренней памяти. При запуске её около 50 КБ.
//
// Флешку открывает, проверяет и монтирует задача usb-drive (стек в PSRAM): открытие
// ждёт готовности флешки до 5 с, и в цикле обмена с Z80 ему не место. Том берут
// в работу только в состоянии «готова» (ready). Вынутую готовую флешку
// отмонтирует ядро 1 (poll, ready) — там, где открываются её файлы; задача её
// только отмечает.
//
// Флешку годной признаёт загрузочный сектор: том FAT32 или exFAT — сам по себе
// или первым разделом таблицы MBR с файловой системой (как ищет том FatFs).
// FAT12/16, NTFS, разметка GPT, неразмеченная флешка — не годятся: ядро работает
// без неё, как прежде.
//
// Внутренняя память. Стеки задач хоста — в PSRAM. Буфер обмена драйвера флешек
// бывает только во внутренней памяти (её одну видит DMA USB у ESP32-S3); драйвер
// растит его под самую большую передачу и не уменьшает, а при неудаче роста
// остаётся с освобождённым буфером. Поэтому передача — не больше буфера: кэши и
// том VFS читают и пишут кусками kTransferBytes, и буфер вырастает до этого размера
// сразу после монтирования, пока память есть.
//
// Файловым серверам (шара SMB «USB», 0.1.174) буфер нужен больше: setTransferBytes
// растит его до kServerTransferBytes, а перед стартом приложения (система однозадачная:
// серверы при этом останавливаются) возвращает kTransferBytes. Сам драйвер буфер не
// меняет: прошивка выделяет новый до освобождения старого, под замком тома FatFs.
// На 0.1.171–0.1.172 шара передавала по 16 КиБ, драйвер вырастил буфер сам и держал
// его до вынимания флешки — 15 872 байта легли в резерв code_ram, и Metal Slug
// получил отказ.
class UsbDrive {
 public:
  static constexpr const char* kMountPoint = "/usb";
  static constexpr const char* kMusicCache = "/usb/SYSTEM/CACHE/MUSIC";
  static constexpr const char* kElfFolder = "/usb/ELF";
  // Ядра ПЛИС с карты Evo (0.1.164, core_store.hpp; пользователь: «в папке /cores/»): ИМЯ.BIN,
  // время файла — как на карте Evo.
  static constexpr const char* kCoreFolder = "/usb/cores";
  // Файлы данных приложений с карты Evo (0.1.165, app_data_files.hpp): папка приложения в нём —
  // /usb/SYSTEM/CACHE/<ПРИЛОЖЕНИЕ> (у Quake 2 — Q2: PAK0.PAK…), рядом с кэшем музыки.
  static constexpr const char* kAppDataRoot = "/usb/SYSTEM/CACHE";
  // Самая большая передача флешке, байтов: кратно сектору (512 и 4096).
  static constexpr uint32_t kTransferBytes = 4096;
  // Буфер передачи на время работы файловых серверов (0.1.174), байтов: кусок TangVfs.
  static constexpr uint32_t kServerTransferBytes = 16384;

  // При старте прошивки (ядро 1): задача usb-drive сама решит, включать ли хост.
  void begin();
  // Каждый проход цикла обмена с Z80 (ядро 1): отмонтировать вынутую флешку.
  void poll();
  // Можно ли сейчас работать с томом флешки (ядро 1). Не ждёт: вставленную при
  // работе флешку задача подключит сама. Флешки нет — изредка (раз в kRetryMs)
  // просит задачу сбросить порт: её подключение могло сорваться.
  bool ready();
  // Почему флешки нет — для строк журнала.
  const char* status() const;
  // Том готов — без побочных действий (не отмонтирует вынутую и не сбрасывает порт), поэтому
  // можно звать из любой задачи (0.1.171: проба шары SMB «USB»). Работать с томом — только после
  // ready() на ядре 1.
  bool isReady() const;
  // Номер монтирования (0.1.171): растёт при каждом новом «готова» — новая флешка или та же снова.
  uint32_t generation() const;
  // Длина буфера передачи драйвера сейчас, байтов (0 — флешка не готова). Передача флешке —
  // не больше этого: иначе драйвер стал бы растить буфер сам.
  uint32_t transferBytes() const;
  // Сделать буфер передачи длиной bytes (0.1.174; кратно сектору, не меньше kTransferBytes).
  // Новый выделяется до освобождения старого: внутренней памяти нет — остаётся прежний. Ждёт
  // замок тома FatFs флешки (передачи идут под ним). Только ядро 1 и только после ready(): там же
  // флешку отмонтируют. Итог — длина буфера после вызова (0 — флешка не готова).
  uint32_t setTransferBytes(uint32_t bytes);

 private:
  void detach();

  uint32_t lastRetryMs_ = 0;
};

UsbDrive& usbDrive();

}  // namespace zifi

#endif  // ZIFI_HAS_USB_DRIVE
