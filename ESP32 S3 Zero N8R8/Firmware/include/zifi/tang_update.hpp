//
//   ESP:    ZIFI-TANG/1 <сборка ESP> <наибольший размер>
//   клиент: BEGIN <размер> <sha256>
//   ESP:    READY <блок>  — или ERROR <причина>
//   клиент: <размер> байтов образа (упакованный .fs Gowin)
//   ESP:    PROGRESS <этап> <сделано> <всего> … и OK <sha256> либо ERROR <причина>
//
// Образ сначала целиком принимается в PSRAM и проверяется: SHA-256, слово синхронизации
// A5C3 и IDCODE GW2AR-18 (0x0000081B) в заголовке, размер — меньше блока с настройками
// (0x7F0000). Только потом стираются блоки 64 КБ с адреса 0, пишется образ и читается
// обратно для сверки. Настройки (сектор 0x7FF000) не трогаются. Новое ядро Tang загрузит
// при следующем включении питания.
//
