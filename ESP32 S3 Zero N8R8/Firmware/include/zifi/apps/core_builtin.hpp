// Встроенный общий слой ядра ПЛИС из кэша BL616 — для ядер без своего ELF на SD Tang
// (/CORES/ИМЯ.ELF): тот же протокол команд Z80, что у слоя ядра NEXT.ELF, и запускается так же
// (плагин VDAC4 Cores, CORE_APP → START):
//   #70 START  [имя ядра, 0]  → F0 [1 — принято]: ядро из кэша BL616 (core_load);
//   #71 INPUT  [любые байты]  → F1 [1]: только знак жизни плагина (клавиш ядру не передаёт);
//   #72 STATUS                → F2 [состояние][VERSION LE32][текст ошибки, 0];
//   #73 EXIT                  → F3 [1]: назад в слот 0 (core_back).
// Состояния: 0 — ждёт START, 1 — грузит ядро, 2 — работает, 3 — назад в слоте 0, 255 — ошибка.
// Плагин молчит дольше 1,5 с (Evo сбросилась) — тоже назад в слот 0. После сеанса снова ждёт
// START.
const zm_app_t* coreBuiltinApp();

