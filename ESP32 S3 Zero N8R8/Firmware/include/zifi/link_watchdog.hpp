#pragma once

#include <stdint.h>

#include "zifi/board.hpp"

#if ZIFI_HAS_SPI_LINK

namespace zifi {

class SpiLink;
class VfsBridge;

// Сторож обмена с Z80 (с vdac4-0.1.43). Своя задача на ядре 0, независимая от
// задачи обмена и от ядра 1, раз в полсекунды смотрит общий буфер SPI:
//   - запрос Z80 лежит в буфере без ответа, а задача обмена за это время не
//     обработала ни одного запроса (и не отвергла ни одного), — она встала;
//   - слово состояния (байты 60..63) не «пусто»/«есть данные» с меткой — Z80
//     будет искать прошивку без конца.
// Если так длится kStuckMs, а Z80 всё это время обращается к ESP, сторож пишет
// в постоянный журнал, на каком шаге стоят задача обмена и ядро 1 (команда,
// операция моста VFS), сколько данных в очередях, что лежит в буфере, — и
// перезапускает ESP. Z80 через секунду видит прошивку снова: без сторожа такое
// зависание снималось только выключением Evo (2026-10-11, после отменённого
// копирования по SMB).
void startLinkWatchdog(SpiLink& link, VfsBridge& bridge);

// Что делает ядро 1 (цикл обмена, Application::pollLink) — для записи сторожа.
enum class CoreStep : uint8_t {
  kPoll = 1,          // ждёт кадр Z80
  kVfs = 2,           // мост VFS: обмен с картой Evo через Z80
  kNetwork = 3,       // ответ и события сетевого ядра
  kCommand = 4,       // разбирает команду Z80 (detail — её код)
};
void coreStep(CoreStep step, uint8_t detail = 0);

}  // namespace zifi

#endif  // ZIFI_HAS_SPI_LINK
