#pragma once

#include <stdint.h>

#include "zifi/board.hpp"

#if ZIFI_HAS_SPI_LINK

namespace zifi {

// Меню настроек Tang (ядро 1.10+): ESP рисует его в оверлей 0 (tang_overlay) — раньше его
// рисовало само ядро (fb_osd); вывод меню — только так. Только настройки, как у прежнего
// меню: фаза, задержка и клок мультиплексора, поправки окна, AUTO ALIGN, SD READ и
// калибровка, ASPECT, SIZE, FRAME BLEND (ядро TS-Config 1.32+: среднее двух кадров Evo —
// мерцание демо ровным цветом), источник. Состояние входа (растр, PCLK, окно, SDRAM) — в
// сетевой консоли («tang»), не в меню.
//
// Ведёт меню только плагин WC с клавиатуры Evo (UI_KEY в TANG_WRITE): 1 — следующий пункт,
// 2 — предыдущий, 3 — значение +1, 4 — −1, 5 — показать меню, 6 — скрыть. Скрытое меню
// первое нажатие (кроме «скрыть») только показывает. После запуска меню скрыто; через 20 с
// без нажатий скрывается само (плагин повторяет «показать» раз в 5 с); кнопки Tang не
// используются. Настройки уходят в Tang (CTRL, ADJUST), во flash их сохраняет tang_flash.
namespace tang_menu {

// Задача Tang (tang_link.cpp): после запуска LINK — begin(), затем poll() каждые ~20 мс.
void begin();
void poll(uint32_t nowMs);
// Меню на ESP (ядро с оверлеями): UI_KEY разбирает ESP, в Tang его не писать.
bool active();
// Нажатие (UI_KEY от плагина WC) — из любой задачи.
void key(uint8_t code);
// Экран проигрывателя (player_overlay) занимает регион оверлеев и задевает конец холста меню:
// меню скрыться и при следующем показе записать свой холст в Tang заново. Из любой задачи.
void yield();

}  // namespace tang_menu
}  // namespace zifi

#endif  // ZIFI_HAS_SPI_LINK
