#pragma once

#include <stddef.h>
#include <stdint.h>

#include "zifi/board.hpp"

#if ZIFI_HAS_SPI_LINK

namespace zifi {
namespace link_spi3 {

// Аппаратный QSPI-ведущий на контроллере SPI3 без драйвера ESP-IDF (spi_master).
//
// Почему без драйвера: в этой прошивке spi_bus_initialize() для SPI3 вешает ESP — внутри
// spicommon_bus_initialize_io(), на любых выводах и без платы (проверено на столе пробами
// 0.1.54–0.1.61: interrupt watchdog, PC в обработчике прерываний). Те же операции —
// тактирование, сброс, маршрутизация выводов через матрицу GPIO — выполненные своим кодом,
// проходят. Поэтому здесь контроллер готовится вручную, а транзакции ведёт HAL (spi_hal_*)
// опросом: ни шины-замка драйвера, ни очередей, ни выделения прерываний.
//
// Транзакция полудуплексная: команда 8 бит по IO0, адрес 32 бита по IO0…IO3, для чтения —
// такты разворота, данные по IO0…IO3. CS — обычный вывод GPIO.

struct Pins {
  int sck;
  int cs;
  int io0;
  int io1;
  int io2;
  int io3;
};

// Запустить контроллер и подключить выводы. Вызывать один раз.
bool begin(const Pins& pins, uint32_t hz);
// Сменить частоту LINK_SCK (без компенсации задержки матрицы GPIO лишними тактами:
// число тактов разворота должно совпадать с ведомым).
bool setClock(uint32_t hz);
uint32_t clockHz();

// Одна транзакция; слова — 32 бита, на линии старшим байтом вперёд; не больше 16 слов.
bool transfer(uint8_t command, uint32_t address, uint32_t* words, size_t count, bool reading,
              int dummyCycles);

// Запись слов подряд в один и тот же адрес (окно FT_DATA Tang — адрес за слово ведомый
// двигает сам): по транзакции в одно слово, но контроллер настраивается один раз, а на
// слово — только данные, старт и CS. Слов — сколько угодно.
bool writeRepeat(uint8_t command, uint32_t address, const uint32_t* words, size_t count);

// Запись слов транзакциями по 16 (буфер контроллера — 64 байта, без DMA) на один и тот же
// адрес: окно FT_BURST Tang (ядро 1.29) кладёт слова в очередь окна FT812 по порядку, адрес
// LINK внутри окна ему не важен. Контроллер настраивается один раз. Слов — сколько угодно.
bool writeBurst(uint8_t command, uint32_t address, const uint32_t* words, size_t count);

// ---------------------------------------------------------------------------------------------
// Длинные транзакции записи через DMA (0.1.176, запрос Quake 2 от 27.11.2026).
//
// Зачем. writeBurst кладёт слова в буфер контроллера W0…W15 сам процессор: транзакция — не длиннее
// 16 слов (64 байта), и на каждую уходит ~5 мкс сверх самой передачи (CS, копирование, запуск,
// опрос). На плате Q2 так получил ~1,75 слова/мкс при 40 МГц, а линия даёт ~5 слов/мкс.
//
// Как. Контроллер SPI3 берёт данные не из W0…W15, а из канала GDMA (общий DMA ESP32-S3): тот сам
// читает слова из памяти и подаёт их в очередь контроллера. Транзакция — до kDmaWords слов. Буфера
// два («пинг-понг»): пока DMA шлёт один, процессор копирует в другой следующий кусок — с разворотом
// байтов (на линии слово идёт старшим байтом вперёд, а в памяти ESP оно младшим байтом вперёд).
// Буферы — во внутреннем ОЗУ, которое видно DMA; память приложения может лежать где угодно (PSRAM).
//
// Память и канал берутся при первом вызове (dmaPrepare) и отдаются dmaRelease — при выгрузке
// приложения: постоянно внутреннее ОЗУ не занимается.
//
// «Без ожидания». writeBurstDma с wait = false возвращается, как только запущена последняя
// транзакция; CS тогда ещё низкий. Каждый следующий обмен этого модуля (transfer, writeRepeat,
// writeBurst, writeBurstDma, setClock, dmaWait) сначала дожидается её конца и поднимает CS. Все
// они идут под замком LINK (tang_link.cpp), поэтому «чужой» обмен на линию не попадёт.
// Слов в одной транзакции DMA: 1 КБ, ~52 мкс на 40 МГц. В 0.1.176 было 512 (2 КБ); 0.1.177 — 256: у Quake 2
// в игре свободно ~21 КБ внутреннего ОЗУ, а минимум доходил до 10,5 КБ, и пользователь выбрал буферы
// 2 × 1 КБ (27.11.2026). Скорость почти та же: ~4,7 слова/мкс против ~4,8 — накладные ~3 мкс на
// транзакцию малы и против 52 мкс передачи.
constexpr size_t kDmaWords = 256;

// Взять буферы DMA (2 × 1 КБ внутреннего ОЗУ) и канал GDMA, если их ещё нет. false — не хватило
// памяти или канала (тогда остаётся writeBurst). keepInternal — сколько внутреннего ОЗУ должно
// остаться свободным после выделения (запас для Wi-Fi и обмена с Evo).
bool dmaPrepare(size_t keepInternal);
bool dmaPrepared();
// Отдать буферы и канал (дождавшись транзакции, если она ещё идёт).
void dmaRelease();

// Слова на один адрес транзакциями до kDmaWords через DMA. Каждая транзакция начинается с address;
// внутри неё ведомый, как всегда, ведёт адрес +4 за слово. Нужен dmaPrepare. wait = false — не
// ждать конца последней транзакции (см. выше). false — транзакция не кончилась за срок.
bool writeBurstDma(uint8_t command, uint32_t address, const uint32_t* words, size_t count, bool wait);
// Дождаться транзакции DMA, запущенной без ожидания. false — она не кончилась за срок или с прошлой
// проверки такая уже была (ошибка «хвоста» не теряется, даже если его дождался чужой обмен).
bool dmaWait();

// Счётчики DMA с запуска ESP — для команды консоли «tang». Только оперативная память.
struct DmaStats {
  uint32_t calls = 0;          // вызовов writeBurstDma
  uint32_t transactions = 0;   // транзакций DMA
  uint64_t words = 0;          // слов
  uint32_t starved = 0;        // транзакций, где DMA не успевал за линией (контроллер ждал данных)
  uint32_t failed = 0;         // транзакций, не кончившихся за срок
};
DmaStats dmaStats();

}  // namespace link_spi3
}  // namespace zifi

#endif  // ZIFI_HAS_SPI_LINK
