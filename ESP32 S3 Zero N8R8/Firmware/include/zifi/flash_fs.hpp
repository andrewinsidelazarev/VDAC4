#pragma once

namespace zifi {

// LittleFS во flash ESP (раздел "littlefs", путь /littlefs) — общий для
// журнала наладки, настроек и кэша модулей ESP. Монтирование со счётчиком:
// раздел размонтируется, только когда его отпустил последний пользователь.
// Журнал и настройки по-прежнему монтируют его на время записи, а кэш модулей
// держит смонтированным всё время: прежде каждый сброс журнала размонтировал
// раздел (LittleFS.end()), и кэш модулей оставался без файловой системы.
//
// formatOnFail — отформатировать раздел, если он не монтируется (только
// когда он ещё никем не смонтирован).
bool flashFsMount(bool formatOnFail);
void flashFsUnmount();

}  // namespace zifi
