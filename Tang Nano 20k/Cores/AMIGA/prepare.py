# 31.10.2026, debug5. Такт SDRAM приходит на вывод на ~5 нс позже внутреннего фронта.
# При 180 градусах чтение шло на левом краю окна (setup -0,47 нс при tAC 6 нс): на плате
# RTE читал со стека 00F1 вместо 00F9, отсюда жёлтый экран Kickstart и точки на картинке.
# Контроллер целиком по спаду clk85, регистры DQ по фронту, расписание прежнее.
sdram=sdram.replace('always @(negedge clk) dq_q','always @(POS clk) dq_q')
sdram=sdram.replace('always @(negedge clk)\n      dq_out','always @(POS clk)\n      dq_out')
assert sdram.count('always @(POS clk)')==2 and sdram.count('always @(negedge clk')==0
sdram=sdram.replace('always @(posedge clk','always @(negedge clk')
sdram=sdram.replace('always @(POS clk)','always @(posedge clk)')
# Цепь sd_dq до выводов не проверяется STA и занимает до 5,4 нс: выводы DQ включаются
