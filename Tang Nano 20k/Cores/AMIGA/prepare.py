# Capture the 32 DQ pins before the half-word mux, as in the working VDAC4
# Next/Slot1 controllers. No enable/reset/logic before this register: Gowin can
# pack it into IREG. Capture at the falling edge before each original read
# state, leaving half a clk85 period for the IREG-to-output path. Keep the
# unused 16-bit configuration unchanged.
sdram=(UP/'src/misc/sdram.sv').read_text(encoding='utf-8')
sdram=sdram.replace('localparam STATE_LAST       = STATE_READ_3;',
    'localparam STATE_LAST       = STATE_READ_3;\nlocalparam STATE_READ_DATA  = STATE_READ_0;')
assert sdram.count('assign ram_dout_lo = sd_data[15: 0];')==1
sdram=sdram.replace('assign ram_dout_lo = sd_data[15: 0];',
    'reg [31:0] dq_q;\n    always @(negedge clk) dq_q <= sd_data;\n    assign ram_dout_lo = dq_q[15: 0];')
sdram=sdram.replace('assign ram_dout_hi = sd_data[31:16];','assign ram_dout_hi = dq_q[31:16];')
# Give every physical DQ pin its own output register. The original duplicated
# 16-bit register drives two pads and cannot be packed into their OREGs.
# ram_din/addr_0 are latched at RAS, two edges before WRITE, so this adds no
# command latency. Use the same falling-edge clock as IREG: opposite I/O clock
# polarities cause Gowin to unpack IREG when packing OREG. The inactive half is
# masked by the existing registered DQM;
# clearing it also prevents synthesis merging the two sets of output flops.
old='assign sd_data     = sd_dq ? {ram_din, ram_din} : {DATA_WIDTH{1\'bz}};'
assert sdram.count(old)==1
sdram=sdram.replace(old,'''reg [31:0] dq_out;
    always @(negedge clk)
      dq_out <= addr_0 ? {16'b0, ram_din} : {ram_din, 16'b0};
    assign sd_data = sd_dq ? dq_out : {DATA_WIDTH{1'bz}};''')
assert sdram.count('STATE_READ_0: begin\n      case (sdram_port)')==1
