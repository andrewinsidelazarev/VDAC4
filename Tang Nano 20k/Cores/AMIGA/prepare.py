# Local adaptations preserve the pinned upstream tree and make regeneration exact.
# PLL как в upstream: CLKOUTD3 растёт на спаде CLKOUT, CLKOUTP 270 градусов идёт
# на вывод такта SDRAM. Контроллер SDRAM работает по спаду clk85 (вместе с clk28),
