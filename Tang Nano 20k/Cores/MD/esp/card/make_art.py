"""Оригинальный пиксель-арт Mega Drive для VDAC4, без текста и логотипов.

Запуск: python -B make_art.py (нужен Pillow).
Все координаты целочисленные; без сглаживания, alpha только 0/255.
Палитра, подиум и масштаб — из cores_ui/tools/generate_art.py.
Записывает только image.png и icon.png рядом с этим сценарием.
"""
from math import cos, sin, tau
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent
COLORS = [
    '#000000', '#090f1d', '#172332', '#293a4b', '#405365', '#698294',
    '#a4b3ba', '#d3dbd8', '#f0ede1', '#c0bba8', '#8b8d80', '#ece2c5',
    '#d8ccb0', '#aaa28e', '#616c6e', '#e46b58', '#ffa76e', '#f2cd70',
    '#79c48d', '#63d4c4', '#559cc6', '#8d92c8', '#c9a2ef', '#344856',
]


def machine():
    im = Image.new('P', (256, 128), 0)
    im.putpalette([c for s in COLORS for c in bytes.fromhex(s[1:])]
                  + [0] * (768 - len(COLORS) * 3))
    d = ImageDraw.Draw(im)

    # Точно тот же подиум и нижний блик, что у NES, NEXT и AMIGA.
    d.polygon([(18, 105), (210, 95), (250, 110), (54, 124)], fill=1)
    d.line([(34, 119), (207, 110)], fill=3)

    # Проекция крышки: фронтальная кромка поднимается вправо, виден левый бок.
    def p(u, v, down=0):
        return round(62 + u + 0.54 * v), round(29 - 0.085 * u + 0.63 * v + down)

    def surface(points, color):
        d.polygon([p(u, v) for u, v in points], fill=color)

    def stroke(points, color, width=1):
        d.line([p(u, v) for u, v in points], fill=color, width=width)

    def disc(u, v, ru, rv, color):
        surface([(u + ru * cos(tau * i / 64), v + rv * sin(tau * i / 64))
                 for i in range(64)], color)

    outline = [(7, 0), (124, 0), (132, 8), (132, 55),
               (124, 63), (8, 63), (0, 55), (0, 8)]
    # Низкий корпус со скруглёнными углами, тёмный фронт и подсвеченный бок.
    d.polygon([p(u, v, 17) for u, v in outline], fill=1)
    for a, b, color in (((0, 8), (0, 55), 3), ((0, 55), (8, 63), 3),
                        ((8, 63), (124, 63), 2), ((124, 63), (132, 55), 2),
                        ((132, 55), (132, 8), 2)):
        d.polygon([p(*a), p(*b), p(*b, 16), p(*a, 16)], fill=color)
    surface(outline, 2)
    stroke(outline + [outline[0]], 4)
    stroke([(7, 0), (124, 0), (132, 8)], 5)
    d.line([p(0, 8), p(0, 55), p(8, 63), p(124, 63), p(132, 55)], fill=5)
    d.line([p(8, 63, 13), p(124, 63, 13), p(132, 55, 13)], fill=3)
    d.line([p(0, 18, 5), p(0, 49, 5)], fill=4)

    # Круглая площадка, спроецированная в плоскость крышки; тонкий светлый обод.
    disc(79, 29, 43, 27, 4)
    disc(79, 29, 40, 24, 1)
    disc(79, 30, 37, 21, 2)
    stroke([(79 + 40 * cos(tau * i / 64), 29 + 24 * sin(tau * i / 64))
            for i in range(33, 57)], 5)

    # Щель картриджа с двумя губками, без вставленного картриджа.
    surface([(48, 16), (110, 16), (113, 19), (113, 25), (47, 25), (45, 22)], 4)
    surface([(48, 18), (110, 18), (110, 23), (48, 23)], 1)
    stroke([(48, 17), (109, 17)], 5)
    stroke([(49, 25), (111, 25)], 3)

    # Вентиляционные прорези слева, два движка и красный индикатор питания.
    for v in range(10, 33, 4):
        surface([(6, v), (28, v), (28, v + 2), (6, v + 2)], 1)
        stroke([(7, v - 1), (27, v - 1)], 3)
    surface([(13, 42), (33, 42), (33, 48), (13, 48)], 1)
    surface([(16, 42), (24, 42), (24, 47), (16, 47)], 4)
    stroke([(16, 42), (24, 42)], 6)
    surface([(36, 53), (51, 53), (51, 59), (36, 59)], 1)
    surface([(39, 53), (47, 53), (47, 58), (39, 58)], 4)
    stroke([(39, 53), (47, 53)], 5)
    surface([(19, 54), (24, 54), (24, 58), (19, 58)], 15)
    stroke([(19, 54), (22, 54)], 16)

    # Два порта на передней грани.
    for u in (84, 108):
        d.polygon([p(u, 63, 4), p(u + 14, 63, 4),
                   p(u + 12, 63, 10), p(u + 2, 63, 10)], fill=1)
        d.line([p(u + 3, 63, 5), p(u + 11, 63, 5)], fill=4)

    # Кабель лежит на подиуме; ближний конец уйдёт под геймпад.
    d.line([p(91, 63, 8), (194, 90), (179, 102), (159, 105),
            (145, 99), (131, 84), (96, 80)], fill=1, width=4)
    d.line([p(91, 63, 8), (194, 90), (179, 102), (159, 105),
            (145, 99), (131, 84), (96, 80)], fill=4, width=2)

    # Изогнутый трёхкнопочный пад: две рукоятки и вогнутый передний край.
    pad = [(30, 94), (34, 86), (43, 81), (59, 79), (78, 80),
           (93, 80), (109, 77), (125, 75), (136, 78), (145, 85),
           (150, 96), (149, 104), (143, 110), (135, 111), (125, 107),
           (114, 100), (102, 99), (87, 101), (75, 107), (63, 114),
           (51, 116), (41, 113), (34, 106), (30, 99)]
    d.polygon([(x, y + 4) for x, y in pad], fill=1)
    d.line([(x, y + 4) for x, y in pad[10:]], fill=4)
    d.polygon(pad, fill=3)
    d.line(pad + [pad[0]], fill=4)
    d.line(pad[:10], fill=5)
    d.line([(34, 94), (38, 88), (46, 85), (58, 83), (72, 84)], fill=4)
    d.line([(44, 111), (52, 113), (62, 111), (75, 103)], fill=2, width=2)
    d.line([(124, 103), (135, 108), (142, 106)], fill=2, width=2)

    # Крестовина на круглом углублении, с фасками для маленькой иконки.
    d.ellipse((43, 86, 70, 107), fill=2)
    d.polygon([(53, 87), (61, 87), (61, 94), (69, 94), (69, 100),
               (61, 100), (61, 107), (53, 107), (53, 100), (45, 100),
               (45, 94), (53, 94)], fill=5)
    d.polygon([(55, 89), (59, 89), (59, 96), (66, 96), (66, 99),
               (59, 99), (59, 104), (55, 104), (55, 99), (48, 99),
               (48, 96), (55, 96)], fill=1)

    # Start и ровно три круглые кнопки; никаких букв и знаков.
    d.polygon([(80, 86), (91, 85), (94, 88), (82, 90)], fill=1)
    d.line([(81, 86), (90, 85)], fill=6)
    for x, y in ((108, 92), (121, 87), (134, 85)):
        d.ellipse((x - 6, y - 4, x + 5, y + 6), fill=1)
        d.ellipse((x - 5, y - 4, x + 4, y + 3), fill=4)
        d.line([(x - 3, y - 4), (x + 1, y - 4)], fill=6)

    im.info['transparency'] = 0
    return im


def main():
    image = machine().convert('RGBA')
    image.save(ROOT / 'image.png')
    image.resize((56, 28), Image.Resampling.NEAREST).save(ROOT / 'icon.png')
    print('image.png: 256x128; icon.png: 56x28; alpha: 0/255')


if __name__ == '__main__':
    main()
