/*
 * Кэш ядер ПЛИС во flash BL616 (core_cache.c, docs/next-core.md) — протокол почтового ящика.
 * Ящик тот же, что у обновления прошивки (fw_mailbox.h: 512 слов в cp_link, ESP пишет его по
 * LINK, заголовок — последним), метка команд другая — 0xB7. Слова:
 *   0      заголовок {0xB7, команда, номер};
 *   1      BEGIN — размер образа, байт; DATA — байтов в посылке;
 *   2      DATA — смещение посылки в образе;
 *   2…9    BEGIN, FIND, LOAD — SHA-256 образа (digest[0…31] подряд, младший байт слова первым);
 *          у LOAD нули — любой;
 *   10…13  BEGIN, FIND, LOAD — имя ядра: 16 байт, в конце нуль (ESP пишет имя заглавными);
 *   16…511 DATA — данные (до 1984 байт), младший байт слова первым.
 * Команды:
 *   BEGIN — начать запись ядра (двоичный битстрим Gowin .bin). Место — по кругу за последним
 *           записанным; ядра, что лежат на этом месте, сразу вычёркиваются из каталога;
 *   DATA  — кусок по порядку: смещение — сколько уже принято (повтор принятого — просто OK).
 *           Посылка, которой нужен новый блок flash (64 КБ), отвечает позже — стирание до ~2 с;
 *   END   — проверка записанного во flash: SHA-256, синхрослово и IDCODE GW2AR-18, адрес
 *           перехода multiboot 0 (возврат — в слот 0), метка VDAC4 в UserCode; ядро — в каталог
 *           (прежнее с тем же именем вычёркивается);
 *   ABORT — бросить запись;
 *   FIND  — есть ли ядро: FOUND — с тем же SHA-256, STALE — имя есть, SHA-256 другой, NONE;
 *   LOAD  — загрузить ядро в SRAM ПЛИС по JTAG (core_jtag.c): BL616 сверяет SHA-256 во flash,
 *           отвечает LOADING и через 50 мс стирает ПЛИС. Ядро заработало — ESP видит его по LINK
 *           (ID, VERSION); не вышло — ПЛИС снова грузится из flash Tang, а в CP_INFO, как только
 *           ядро VDAC4 ответит, — LOAD_FAIL | код core_jtag (0x27 — не тот UserCode);
 *   INFO  — в поле состояния — объём flash BL616, МБ (0 — кэша нет; 0xFF — каталога нет, а место
 *           не чистое: там чьи-то данные, кэш выключен);
 *   FORMAT — слово 1 = CC_FORMAT_KEY: создать пустой каталог (чужие данные на месте кэша
 *           пропадут) — только по слову пользователя;
 *   BOOT  — (прошивка 35) слово 1 — адрес слота flash Tang (кратен CC_SLOT_BYTES, меньше
 *           CC_SLOT_END; ядро видео — 0x300000): отвечает LOADING, через 50 мс стирает ПЛИС, по
 *           JTAG шлёт заголовок битстрима с этим адресом перехода и делает Reconfig
 *           (core_jtag_boot) — ПЛИС грузит битстрим слота. Пришло ли ядро — ESP видит по LINK;
 *           BL616 ведёт его, как ядро из кэша, а не отвечает оно 3 с — переходит в слот 0.
 *           Битстрим в слоте проверяет ESP до команды (синхрослово, IDCODE, адрес перехода 0).
 *           Прошивка до 35 отвечает BAD_CMD.
 * Ответ — слово CP_INFO (LINK 0x30): {0xC2, состояние, номер команды}. Новой команды нет 10 с —
 * запись брошена.
 */
#ifndef CORE_MAILBOX_H
#define CORE_MAILBOX_H

#define CC_MAGIC      0xB7u
#define CC_INFO_MAGIC 0xC2u

enum { CC_BEGIN = 1, CC_DATA = 2, CC_END = 3, CC_ABORT = 4, CC_FIND = 5, CC_LOAD = 6, CC_INFO = 7,
       CC_FORMAT = 8, CC_BOOT = 9 };
#define CC_FORMAT_KEY 0x21544D46u     /* "FMT!" */
#define CC_SLOT_BYTES 0x100000u       /* слот multiboot flash Tang (XT25F64B, 8 МБ) */
#define CC_SLOT_END   0x700000u       /* слоты 0…6; с 0x7F0000 — настройки кадрового буфера */

#define CC_W_SIZE  1u
#define CC_W_OFF   2u
#define CC_W_SHA   2u
#define CC_W_NAME 10u
#define CC_NAME_LEN 16u

enum {
    CC_OK = 0x00,
    CC_BAD_CMD = 0x01,        /* DATA/END без BEGIN, неизвестная команда */
    CC_BAD_SIZE = 0x02,       /* меньше 4 КБ или больше места кэша */
    CC_BAD_OFFSET = 0x03,     /* посылка не по порядку или за концом; END — принято не всё;
                                 BOOT — адрес не начало слота */
    CC_BAD_SHA = 0x04,        /* SHA-256 во flash не тот (LOAD: ядро вычеркнуто) */
    CC_BAD_IMAGE = 0x05,      /* не битстрим GW2AR-18 или адрес перехода не 0 */
    CC_NO_MARK = 0x06,        /* нет метки VDAC4 в UserCode — ядро не для VDAC4 */
    CC_FLASH = 0x07,          /* стирание или запись flash BL616 не прошли */
    CC_BAD_NAME = 0x08,       /* пустое имя или без нуля в 16 байтах */
    CC_FOREIGN = 0x09,        /* кэш выключен: на его месте чьи-то данные (FORMAT) */
    CC_LOADING = 0x10,        /* LOAD: ядро верно, BOOT: адрес верен — через 50 мс ПЛИС стирается */
    CC_FOUND = 0x11,
    CC_STALE = 0x12,
    CC_NONE = 0x13,
    CC_LOAD_FAIL = 0x20,      /* | код core_jtag: 1 нет ПЛИС … 6; 7 — UserCode после загрузки не тот */
};

/* Метка VDAC4 в конце битстрима: команда UserCode 0A 00 00 00 и значение 56 44 34 xx (xx —
   личность ядра: 03 — ZX Next) */
#define CC_MARK 0x564434u

#endif
