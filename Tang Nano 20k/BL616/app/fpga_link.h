/* Связь BL616 с ПЛИС Tang (fpga/vdac2/rtl/cp_spi.sv, cp_link.sv) — шина сопроцессора FT812. */
#ifndef FPGA_LINK_H
#define FPGA_LINK_H

#include "ft_copro.h"

/* SPI0 и IRQ; 0 — ПЛИС ответила снимком STATUS с меткой C5 01. */
int fpga_link_init(void);
/* 1 — IRQ_N низкий: у сопроцессора есть работа */
int fpga_irq(void);
/* шина для ftc_init */
void fpga_bus(ftc_bus_t *bus);
/* Слово состояния прошивки — ESP видит его в LINK 0x30 CP_INFO (cp_link, адрес 0x3FFFFC). */
void fpga_info(uint32_t v);
/* 1 — в последнем снимке STATUS ядро просит перезагрузку ПЛИС (бит 7 флагов, ядро 1.13+):
   её делает BL616 командой JTAG Reconfig (fpga_jtag.c) */
int fpga_boot_requested(void);
/* Один снимок STATUS (обновляет запрос перезагрузки): 0 — ПЛИС ответила меткой C5 01. Для ядра
   из кэша (core_cache.c) — у него нет ни ящика, ни сопроцессора, только STATUS. */
int fpga_status_poll(void);
/* запись без ожидания (шина: wr_async): продвинуть и дождаться конца */
void fpga_pump(void);
void fpga_wr_wait(void);
/* частота записи: 40 МГц до самопроверки, после неё — 80 или 40; 20 — если проверка первых
   посылок не сошлась */
uint32_t fpga_write_hz(void);
/* Самопроверка частот записи и чтения (прошивка 9): 2 — запись 40 МГц, 3 — 80; -1 — ядра
   FT812 нет (образец на 20 МГц не сошёлся), повторить позже. Отчёт — 32 слова в RAM_G с
   FPGA_REPORT_ADDR (64 КБ на замер): [0] метка, [1] частота записи, [2] частота слов чтения,
   [3] бит 0 — непрерывный режим SPI, бит 1 — слова чтения по 32 бита; запись 80 МГц с паузами
   [4…8] и непрерывно [9…13] — ошибок, мкс всего, мкс DMA, мкс ожидания места, снимков; запись
   40 МГц непрерывно [14, 15] — ошибок, мкс; чтение — ошибок и мкс: 20 МГц по байту [16, 17],
   20 по 32 бита [18, 19], 40 [20, 21], 53,3 (фазы 2+1) [22, 23], 53,3 (1+2) [24, 25], 80 [26, 27]. */
#define FPGA_REPORT_ADDR  0x1DFF00u
#define FPGA_REPORT_MAGIC 0x32445053u   /* "SPD2" */
int fpga_speed_test(void);
/* счётчики: посылок SPI, повторов опроса */
extern uint32_t fpga_xacts, fpga_waits;
/* Чтений и записей, брошенных без готовности (ядро без чтения, ПЛИС пропала) — для журнала. */
uint32_t fpga_stuck(void);

#endif
